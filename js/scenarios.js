  /** Найти сценарий по идентификатору. */
  function getScenario(scenarioId) {
    for (var i = 0; i < SCENARIOS.length; i++) {
      if (SCENARIOS[i].id === scenarioId) return SCENARIOS[i];
    }
    return null;
  }

  /** Данные роли внутри сценария + общее описание роли. */
  function getRole(scenarioId, roleId) {
    var scenario = getScenario(scenarioId);
    if (!scenario) return null;
    var role = scenario.roles[roleId];
    if (!role) return null;
    var intro = ROLE_INTRO[roleId] || {};
    return {
      scenarioId: scenario.id,
      scenarioTitle: scenario.title,
      scenarioEmoji: scenario.emoji,
      roleId: roleId,
      label: intro.label || roleId,
      emoji: intro.emoji || '🎤',
      summary: intro.summary || '',
      hint: intro.hint || '',
      duration: role.duration,
      goal: role.goal,
      instructions: role.instructions,
      tips: role.tips,
      cheatSheet: role.cheatSheet,
      allTips: role.tips.concat(GLOBAL_TIPS)
    };
  }

  /** Список ролей сценария в порядке: инициатор, респондент, модератор. */
  function listRoles(scenarioId) {
    var scenario = getScenario(scenarioId);
    if (!scenario) return [];
    return ['initiator', 'respondent', 'moderator']
      .filter(function (roleId) { return Boolean(scenario.roles[roleId]); })
      .map(function (roleId) { return getRole(scenarioId, roleId); });
  }

